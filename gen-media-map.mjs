// Turn the upload manifest + harvested GHL ids into site/js/media-map.js.
//
//   upload-staging/_manifest.json   sitePath   -> uploadName
//   bv-media-ids.json               uploadName -> ghl id
//   => site/js/media-map.js         sitePath   -> ghl id
//
// The site keeps using its ordinary relative paths; media() swaps in the CDN
// URL when one is known, so the local preview still works untouched.
import fs from 'node:fs';
import path from 'node:path';

const STAGE = 'upload-staging';
const IDS = process.argv[2] ||
  'C:/Users/ahmed/AppData/Local/Temp/claude/C--Users-ahmed-OneDrive-Documents-ClaudeWork/972c0489-13ac-4d9c-ab89-4122faaee4d9/scratchpad/bv-media-ids.json';
const OUT = 'site/js/media-map.js';
const BASE = 'https://assets.cdn.filesafe.space/PWyhncZ0y766gD1TL1PO/media/';

const manifest = JSON.parse(fs.readFileSync(path.join(STAGE, '_manifest.json'), 'utf8'));

/* Every path on the command line is merged, later files winning. The library is
   harvested in batches — the original 196 in one session, the 378 light copies
   in another — and re-harvesting everything to add one file would be silly.
   `tools/harvest-media-ids.js` is what produces these. */
const sources = process.argv.slice(2).filter((a) => !a.startsWith('-'));
const ids = {};
for (const src of sources.length ? sources : [IDS]) {
  if (!fs.existsSync(src)) { console.warn('  (no such ids file: ' + src + ')'); continue; }
  Object.assign(ids, JSON.parse(fs.readFileSync(src, 'utf8')));
}

/* Refuse to write an empty map. The ids file lives outside the repo, so a
   missing path here used to produce a valid-looking media-map.js with nothing
   in it — which silently un-hosts all 196 assets and points the live site at
   relative paths that do not exist. Overwriting a working map with nothing is
   never the intended outcome of running this. */
if (!Object.keys(ids).length) {
  console.error('No ids in ' + IDS);
  console.error('Pass the harvested uploadName -> GHL id JSON as argv[2].');
  console.error('Refusing to overwrite ' + OUT + ' with an empty map.');
  process.exit(1);
}

const map = {};
const missing = [];
for (const m of manifest) {
  const id = ids[m.uploadName];
  if (id) map[m.sitePath] = id;
  else missing.push(m.sitePath + '  (' + m.uploadName + ')');
}

const keys = Object.keys(map).sort();
const pad = Math.min(46, keys.reduce((a, k) => Math.max(a, k.length), 0) + 3);
const body = keys.map(k => "  '" + k + "':" + ' '.repeat(Math.max(1, pad - k.length)) + "'" + map[k] + "',").join('\n');

fs.writeFileSync(OUT,
`/* GENERATED by gen-media-map.mjs — do not hand-edit.
   Maps a site-relative asset path to its id in the GHL "demo cairo" media
   library, folder "Beeviro Portfolio".

   GHL discards filenames on upload and returns an opaque id, so every file was
   staged under a UNIQUE flat name first (bv-<slug>-NN.jpg) — the site has 12
   colliding basenames (01.jpg lives in 25 client folders) and a naive flatten
   would have silently overwritten them.

   Anything absent here falls back to the local relative path, so the local
   preview keeps working with no map at all. */
window.BV_MEDIA_BASE = '${BASE}';

window.BV_MEDIA = {
${body}
};
${missing.length ? '\n/* NOT YET UPLOADED (' + missing.length + '):\n' +
  missing.map(m => '     ' + m).join('\n') + '\n*/\n' : ''}`);

console.log('wrote ' + OUT);
console.log('  mapped :', keys.length, '/', manifest.length);
if (missing.length) {
  console.log('  MISSING:', missing.length);
  missing.slice(0, 10).forEach(m => console.log('    ' + m));
}
